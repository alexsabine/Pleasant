"""Tune Crescent Compass from the repository's own mathematics, against the live DB.

What it does (report only unless --apply):
1. Declares per-category hazard priors (Gamma shape, rate) in two classes, places and
   programmes, and folds in any observed changes (superseded claims) by Gamma-Poisson
   conjugacy (pc_core.freshness.GammaRate.update). The priors are labelled `generated`
   (declared, not yet learned) in the hazard notes.
2. Derives, per category, the published consequences: show horizon (age at which
   P(current) falls to p* = 0.75 under utilities +1/-3/0), recheck horizon (P = 0.5), and
   the myopic review value at the show horizon (pc_core.freshness.review_priority).
3. Cross-checks the myopic rule against the exact finite-horizon POMDP
   (pc_core.pomdp.freshness_pomdp + value_dp): the belief below which 'show' stops being
   the Bayes act must agree with p*, and 'verify' must be chosen for beliefs below p*.
4. Turns the horizons into a verification workload for the stewards (checks per week to
   keep every listing recommendable) and simulates a year of that budget with the
   repository's homeostasis loop (pc_core.closure.simulate_verification_loop).
5. Sweeps a corpus of realistic caregiver questions through the intent parser and
   policy and reports any that come back empty on the live projection.
Writes research/07_compass_tuning.md.
"""
from __future__ import annotations

import math
import time
from dataclasses import replace
from collections import Counter
from pathlib import Path

from django.conf import settings
from django.core.management.base import BaseCommand

from atlas.models import CATEGORIES, CategoryHazard, Claim, Event, Resource
from compass import policy
from pc_core.bayes import choose_binary_action
from pc_core.closure import simulate_verification_loop
from pc_core.freshness import GammaRate, prob_current, review_priority
from pc_core.pomdp import freshness_pomdp

# Declared prior classes. Mean hazard = shape/rate per day; shape 2 keeps the prior weak
# (worth two observed changes), so real observations move it quickly.
PLACES = {"school", "college", "library", "park", "playground", "beach", "river", "trail", "museum",
          "attraction", "visitor_center", "indoor_play"}
PROGRAMMES = {"after_school", "class", "sport", "family_service", "health", "food", "childcare",
              "preschool", "arts", "event_venue"}
PRIOR = {"place": (2.0, 1080.0),      # one material change per ~18 months
         "programme": (2.0, 360.0)}   # one material change per ~6 months (terms, seasons, staff)

CORPUS = [
    "somewhere free for a 3 year old", "rainy day ideas for kids", "where can my toddler play",
    "swimming pool", "a beach with tide pools", "an easy redwood walk with a pushchair",
    "what's on this weekend", "after school programs for a 10 year old", "help with parenting",
    "preschool near Smith River", "library story time", "a museum", "sea lions or an aquarium",
    "bowling", "a farm to visit", "art gallery", "junior ranger program", "camping with kids",
    "lighthouse", "harbor", "high school in Crescent City", "head start", "wheelchair accessible playground",
    "picnic by the river", "lake", "4-H club", "dunes", "something for a teenager", "free things under $10",
    "where is the visitor center", "college classes", "a hike in Klamath", "skate park", "trees of mystery",
]


def horizon(prior: GammaRate, p: float) -> float:
    """Age at which the Gamma-exponential survival (rate/(rate+t))^shape equals p."""
    return prior.rate * (p ** (-1.0 / prior.shape) - 1.0)


class Command(BaseCommand):
    help = __doc__

    def add_arguments(self, parser):
        parser.add_argument("--apply", action="store_true", help="write the declared priors into CategoryHazard")
        parser.add_argument("--weekly-budget", type=float, default=None, help="steward checks per week to simulate (default: derived)")

    def handle(self, *args, **opts):
        u = settings.COMPASS_UTILITIES
        p_star = -u["show_false"] / (u["show_true"] - u["show_false"])
        lines = ["# Crescent Compass tuning report (generated)", "",
                 f"Generated by `manage.py tune_compass` on {time.strftime('%Y-%m-%d')}. Utilities (show if current, show if stale, abstain) = "
                 f"({u['show_true']}, {u['show_false']}, {u['abstain']}), so the show threshold is p* = {p_star:.2f}. "
                 "All priors below are *declared* (`generated`); they update by Gamma-Poisson conjugacy as changes are observed.", ""]

        live = list(Resource.objects.filter(live=True, visibility="public"))
        by_cat = Counter(r.category for r in live)
        age_sum = Counter()
        for r in live:
            age_sum[r.category] += r.age_days or 0.0
        changes = Counter(Claim.objects.filter(verification_status="superseded").values_list("resource__category", flat=True))

        # 1 + 2: priors and horizons
        lines += ["## 1. Declared hazard priors and their consequences", "",
                  "| Category | Class | Live | Prior (shape, rate d) | Mean hazard /day | Show horizon (P=p*) | Recheck horizon (P=0.5) | Observed changes / exposure d |",
                  "|---|---|---|---|---|---|---|---|"]
        rows = {}
        for cat, label in CATEGORIES:
            cls = "place" if cat in PLACES else "programme"
            shape, rate = PRIOR[cls]
            h = CategoryHazard.for_category(cat)
            if opts["apply"]:
                h.shape, h.rate = shape, rate
                h.changes_observed, h.exposure_days = changes.get(cat, 0), round(age_sum.get(cat, 0.0), 1)
                h.notes = (f"Declared prior ({cls}): epistemic type generated; tuned by manage.py tune_compass on {time.strftime('%Y-%m-%d')}. "
                           "Updates by conjugacy from superseded claims (changes) over live listing ages (exposure).")
                h.save()
            post = GammaRate(shape, rate).update(changes.get(cat, 0), age_sum.get(cat, 0.0))
            rows[cat] = (cls, post)
            lines.append(f"| {label} | {cls} | {by_cat.get(cat, 0)} | ({shape:.0f}, {rate:.0f}) | {post.mean_hazard:.5f} | {horizon(post, p_star):.0f} d | "
                         f"{horizon(post, 0.5):.0f} d | {changes.get(cat, 0)} / {age_sum.get(cat, 0.0):.0f} |")

        # 3: POMDP cross-check (weekly step; 3-step exact DP)
        # (a) Compass answers with {show, abstain} only: no verification is possible at answer time, so the
        #     exact DP over those two actions must reproduce the myopic threshold p*.
        # (b) With 'verify' available (the stewards' review queue), the DP prefers a check for beliefs in an
        #     uncertain band above p*: that is the review queue's job, not Compass's, and is reported, not asserted.
        lines += ["", "## 2. Exact POMDP cross-check of the myopic rule", ""]
        ok_all = True
        for cls, (shape, rate) in PRIOR.items():
            prior = GammaRate(shape, rate)
            hz = 1 - prior.survival(7.0)   # weekly staleness probability under the prior mean
            full = freshness_pomdp(hazard=hz, sensitivity=0.95, specificity=0.95, show_true=u["show_true"], show_false=u["show_false"], verify_cost=0.1)
            answer_only = replace(full, actions=["show", "abstain"])
            grid = [i / 100 for i in range(101)]
            dp_show = min((p for p in grid if answer_only.value_dp([p, 1 - p], 3)[1] == "show"), default=None)
            myopic = min(p for p in grid if choose_binary_action(p, u["show_true"], u["show_false"], u["abstain"])[0] == "show")
            verify_band = [p for p in grid if full.value_dp([p, 1 - p], 3)[1] == "verify"]
            agree = dp_show is not None and abs(dp_show - myopic) <= 0.0101  # within one grid step; the exact tie at p* is broken by action order
            ok_all &= agree
            lines.append(f"- **{cls}** (weekly hazard {hz:.4f}): answer-time DP over show/abstain first chooses *show* at belief {dp_show}; "
                         f"the myopic rule at {myopic:.2f}: {'agree' if agree else 'DISAGREE'}. With a human check available at cost 0.1, "
                         f"the DP prefers *verify* for beliefs {min(verify_band) if verify_band else '—'}..{max(verify_band) if verify_band else '—'}, "
                         "i.e. a check beats both showing and abstaining across the uncertain band; the admin review queue implements exactly that preference.")
        lines.append("")
        lines.append("Result: " + ("the Compass show rule equals the exact finite-horizon POMDP solution over its own actions for both classes." if ok_all else "DISAGREEMENT; see rows above."))

        # 4: workload and homeostasis
        per_week = 0.0
        mean_hazard = 0.0
        for r in live:
            cls, post = rows[r.category]
            per_week += 7.0 / horizon(post, p_star)
            mean_hazard += post.mean_hazard
        mean_hazard /= max(1, len(live))
        budget = opts["weekly_budget"] or math.ceil(per_week)
        per_day = max(1, round(budget / 7)) if budget >= 7 else 1
        # the simulator takes an integer checks_per_day; run it at the implied daily budget and at one check per day
        sims = {}
        for pol in ("none", "oldest", "evsi", "evsi_repair"):
            res = simulate_verification_loop(n_listings=len(live), days=365, daily_change_prob=mean_hazard, checks_per_day=per_day, policy=pol)
            sims[pol] = (res.final_stale_fraction, max(res.stale_fraction_over_time), res.checks_made)
        lines += ["", "## 3. Steward workload implied by the priors", "",
                  f"- Live public listings: {len(live)}; listing-weighted mean hazard {mean_hazard:.5f}/day (one material change per {1 / mean_hazard:.0f} listing-days).",
                  f"- Rechecking each listing once per show horizon keeps every listing recommendable: **{per_week:.1f} checks per week** ({per_week * 52 / 12:.0f} per month), "
                  f"about {per_week * 10 / 60:.1f} h/week at ten minutes a check.",
                  f"- One-year simulation at {per_day} check/day ({per_day * 7}/week) with the repository's homeostasis loop (daily hazard = mean hazard above):", "",
                  "| Policy | Stale fraction at day 365 | Worst day | Checks made |", "|---|---|---|---|"]
        for pol, (fin, worst, n) in sims.items():
            lines.append(f"| {pol} | {fin:.3f} | {worst:.3f} | {n} |")
        lines.append("")
        lines.append("`evsi_repair` is the policy the admin review queue uses (review_priority with repair_value = 3). "
                     "The budget is the smallest integer checks/day at or above the derived weekly rate.")

        # 5: intent coverage sweep
        lines += ["", "## 4. Intent coverage on the live projection", "",
                  "| Question | Parsed categories | Community | Action | Shown | Withheld |", "|---|---|---|---|---|---|"]
        empty = []
        for q in CORPUS:
            it = policy.parse_intent_rules(q)
            it.text = q
            d = policy.decide(it, max_items=4)
            if d.action in ("explain_unknown",):
                empty.append(q)
            lines.append(f"| {q} | {', '.join(it.categories) or '—'} | {it.community or '—'} | {d.action}{' (' + ', '.join(d.broadened) + ' relaxed)' if d.broadened else ''} | {len(d.shown)} | {len(d.withheld)} |")
        n_events = Event.objects.filter(live=True).count()
        lines += ["", f"Questions that returned nothing: {len(empty)} of {len(CORPUS)}" + (": " + "; ".join(empty) if empty else ".") + f" Live events in the projection: {n_events}.", "",
                  "An empty answer is correct when the projection has no such listing (Compass invents nothing); the sweep exists to catch parser gaps, "
                  "which are fixed by adding keywords in `compass/tools.py`, never by loosening the show test."]

        out = Path(settings.REPO_ROOT) / "research" / "07_compass_tuning.md"
        out.write_text("\n".join(lines) + "\n")
        self.stdout.write("\n".join(lines))
        self.stdout.write(f"\n{'APPLIED' if opts['apply'] else 'report only'}; written to {out}")
